SCD2_COLUMNS = {
    "postgres": [("dt_inicio_validade", "DATE NOT NULL"), ("dt_fim_validade", "DATE"),
                 ("fl_versao_atual", "BOOLEAN NOT NULL DEFAULT TRUE"), ("nr_versao", "INTEGER NOT NULL DEFAULT 1")],
    "oracle": [("dt_inicio_validade", "DATE NOT NULL"), ("dt_fim_validade", "DATE"),
               ("fl_versao_atual", "NUMBER(1) DEFAULT 1 NOT NULL"), ("nr_versao", "NUMBER(10) DEFAULT 1 NOT NULL")],
    "mysql": [("dt_inicio_validade", "DATE NOT NULL"), ("dt_fim_validade", "DATE"),
              ("fl_versao_atual", "TINYINT(1) NOT NULL DEFAULT 1"), ("nr_versao", "INT NOT NULL DEFAULT 1")],
}
SCD2_COMMENTS = {
    "dt_inicio_validade": "Início de vigência da versão (SCD Tipo 2)",
    "dt_fim_validade": "Fim de vigência da versão (nulo = versão vigente)",
    "fl_versao_atual": "Indica a versão atual do registro",
    "nr_versao": "Número sequencial da versão",
}


def _flatten_regular_attrs(ctx, entity):
    """[(coluna, tipo_sql, not_null, atributo, comentário, sub_or_attr)] para atributos persistíveis."""
    cols = []
    for a in entity.attrs:
        if a.is_derived or a.is_multivalued:
            continue
        if a.is_composite and a.sub_attrs:
            for sub in a.sub_attrs:
                cols.append((f"{ctx.s(a.name)}_{ctx.s(sub.name)}", map_type(ctx.d, ctx.attr_type(sub)),
                             sub.nn, a, ctx.comment_of(sub, a), sub))
            continue
        cols.append((ctx.s(a.name), map_type(ctx.d, ctx.attr_type(a)), a.nn, a, ctx.comment_of(a), a))
    return cols


def generate_kimball_ddl(project, dialect="postgres"):
    """Gera DDL de esquema estrela (Kimball) a partir das entidades marcadas como
    'dimension' ou 'fact' (Entity.kimball_role).

    - Dimensões -> `dim_<nome>` com chave substituta `<nome>_sk` (identity), colunas naturais e,
      para SCD Tipo 2, colunas de controle de histórico.
    - Fatos -> `fat_<nome>` com uma FK `<dim>_sk` por dimensão relacionada (via relacionamentos ER)
      e as métricas (atributos numéricos) do fato.
    Descrições e domínios dos atributos são levados para o DDL como no modelo relacional.
    """
    if dialect not in TYPE_MAP:
        raise ValueError(f"Dialeto não suportado: {dialect}")
    c = _Ctx(project, dialect)
    s = c.s
    out = c.out
    dims = [e for e in project.entities if e.kimball_role == "dimension"]
    facts = [e for e in project.entities if e.kimball_role == "fact"]

    out.append("-- ========================================================")
    out.append("-- DDL Dimensional (Modelagem Kimball — Esquema Estrela)")
    out.append(f"-- Dialeto: {dialect.upper()}")
    out.append("-- ========================================================")
    if not dims and not facts:
        out.append("-- Nenhuma entidade foi classificada como Dimensão ou Fato.\n"
                   "-- Edite cada entidade (duplo-clique) e defina o 'Papel Dimensional (Kimball)'\n"
                   "-- como Dimensão ou Fato antes de gerar este DDL.")
        return "\n".join(out)
    out.append("")

    c.emit_domains(_used_domain_ids(project, dims + facts))

    out.append("-- ---------------- TABELAS DIMENSÃO ----------------")
    dim_sk_col = {}
    for d in dims:
        tbl, sk_col = f"dim_{s(d.name)}", f"{s(d.name)}_sk"
        dim_sk_col[d.id] = (tbl, sk_col)
        cols = [c.column(sk_col, identity_clause(dialect, map_type(dialect, "INTEGER")), True,
                         f"Chave substituta da dimensão {d.name}")]
        cons = []
        for col_name, col_type, nn, a, comment, src in _flatten_regular_attrs(c, d):
            cols.append(c.column(col_name, col_type, nn, comment))
            cons.extend(k for k in c.attr_constraints(tbl, col_name, src) if "UNIQUE" not in k)
        if d.scd_type == "scd2":
            for col_name, col_def in SCD2_COLUMNS.get(dialect, SCD2_COLUMNS["postgres"]):
                base_type = col_def.split(" NOT NULL")[0].split(" DEFAULT")[0]
                extra = col_def[len(base_type):].replace(" NOT NULL", "").strip()
                cols.append(c.column(col_name, base_type, " NOT NULL" in col_def or "NOT NULL" in col_def,
                                     SCD2_COMMENTS[col_name], extra=extra))
        scd_note = " (SCD Tipo 2 — mantém histórico de versões)" if d.scd_type == "scd2" \
            else " (SCD Tipo 1 — sobrescreve o valor atual)"
        c.create_table(tbl, cols, [f"CONSTRAINT {c.cname('pk', tbl)} PRIMARY KEY ({sk_col})"] + cons,
                       comment=_flat(d.description) or f"Dimensão {d.name}",
                       pre_comments=[f"-- Dimensão '{d.name}'{scd_note}"])

    out.append("-- ---------------- TABELAS FATO ----------------")
    for f in facts:
        tbl = f"fat_{s(f.name)}"
        sk = f"{s(f.name)}_sk"
        cols = [c.column(sk, identity_clause(dialect, map_type(dialect, "INTEGER")), True,
                         f"Chave substituta do fato {f.name}")]
        fk_cols = []
        rel_dim_pairs = []
        for r in project.rels:
            e1, e2 = project.find_entity(r.entity1_id), project.find_entity(r.entity2_id)
            if not e1 or not e2:
                continue
            if e1.id == f.id and e2.kimball_role == "dimension":
                rel_dim_pairs.append((r, e2))
            elif e2.id == f.id and e1.kimball_role == "dimension":
                rel_dim_pairs.append((r, e1))
        occurrences = {}
        for r, dim in rel_dim_pairs:
            occurrences.setdefault(dim.id, []).append(r)
        related, seen = [], set()
        for r, dim in rel_dim_pairs:
            if dim.id not in dim_sk_col:
                continue
            dim_tbl, sk_col = dim_sk_col[dim.id]
            # Role-playing dimension: mesma dimensão em vários relacionamentos -> FKs distintas
            fk_col = f"{s(r.name)}_{sk_col}" if len(occurrences[dim.id]) > 1 else sk_col
            if fk_col in seen:
                continue
            seen.add(fk_col)
            related.append(dim)
            cols.append(c.column(fk_col, map_type(dialect, "INTEGER"), True,
                                 f"FK para {dim_tbl}.{sk_col} (relacionamento {r.name})"))
            fk_cols.append((fk_col, dim_tbl, sk_col))
        measures = f.measure_attrs()
        cons = []
        for m in measures:
            col = s(m.name)
            cols.append(c.column(col, map_type(dialect, c.attr_type(m)), False,
                                 (c.comment_of(m) + " | " if c.comment_of(m) else "") + "Métrica"))
            cons.extend(k for k in c.attr_constraints(tbl, col, m) if "UNIQUE" not in k)
        measure_ids = {m.id for m in measures}
        for col_name, col_type, nn, a, comment, src in _flatten_regular_attrs(c, f):
            if a.id in measure_ids or a.is_pk:
                continue
            cols.append(c.column(col_name, col_type, nn, comment))
            cons.extend(k for k in c.attr_constraints(tbl, col_name, src) if "UNIQUE" not in k)
        constraints = [f"CONSTRAINT {c.cname('pk', tbl)} PRIMARY KEY ({sk})"]
        constraints += [f"CONSTRAINT {c.cname('fk', tbl, fk)} FOREIGN KEY ({fk}) REFERENCES {dt}({dsk})"
                        for fk, dt, dsk in fk_cols] + cons
        grain = ", ".join(dict.fromkeys(d.name for d in related)) or \
            "não identificada — relacione o fato às dimensões no diagrama"
        c.create_table(tbl, cols, constraints, comment=_flat(f.description) or f"Fato {f.name}",
                       pre_comments=[f"-- Fato '{f.name}' — grão definido pela combinação de: {grain}"])
        for fk, _dt, _dsk in fk_cols:
            out.append(index_stmt(dialect, tbl, [fk], c.cname("idx", tbl, fk)))
        out.append("")

    if dims and not facts:
        out.append("-- Nenhuma tabela Fato foi definida ainda — marque ao menos uma entidade como 'Fato'.")
    if facts and not dims:
        out.append("-- Nenhuma tabela Dimensão foi definida ainda — marque as entidades de contexto como 'Dimensão'.")
    return "\n".join(out)
